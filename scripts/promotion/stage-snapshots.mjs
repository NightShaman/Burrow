import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const TARGETS = {
  burrow: {
    paths: ['.dockerignore', '.gitignore', 'Dockerfile', 'LICENSE', 'README.md', 'SOURCE_VERSIONS', 'backend', 'burrow-logo.png', 'compose.yml', 'docker-entrypoint.sh', 'docs', 'install.sh', 'mkdocs.yml', 'requirements-docs-test.txt', 'requirements-docs.txt', 'scripts/assembly', 'scripts/docs', 'scripts/install', 'ui'],
    excludes: []
  },
  nodeGoblin: {
    paths: ['.gitignore', 'LICENSE', 'NG-Logo.png', 'README.md', 'burrow.mod.json', 'docs', 'gateway', 'install.sh', 'mkdocs.yml', 'requirements-docs-test.txt', 'requirements-docs.txt', 'scripts/docs', 'server', 'ui'],
    excludes: ['docs/audit-repair-pass-5.md', 'docs/repairs/lifecycle-pass-4.md']
  },
  goblinSecretStore: {
    paths: ['API-CONTRACT.md', 'LICENSE', 'README.md', 'burrow.mod.json', 'docs', 'package.json', 'server', 'ui'],
    excludes: []
  },
  burrowSkills: {
    paths: ['LICENSE', 'README.md', 'burrow-runtime', 'docs'],
    excludes: []
  },
  burrowBackdoor: {
    paths: ['README.md', 'LICENSE', 'burrow.mod.json', 'docs', 'package.json', 'package-lock.json', 'src', 'test', 'ui'],
    excludes: []
  }
};

const DATE = /^\d{4}\.\d{2}\.\d{2}$/;
const SHA = /^[0-9a-f]{40}$/;

function run(command, args, options = {}) {
  return execFileSync(command, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'], ...options }).trim();
}

function writeJson(file, value) {
  fs.writeFileSync(file, `${JSON.stringify(value, null, 2)}\n`);
}

function stampJson(file, version) {
  const value = JSON.parse(fs.readFileSync(file, 'utf8'));
  value.version = version;
  if (value.packages?.['']) value.packages[''].version = version;
  writeJson(file, value);
}

export function validateInputs({ releaseDate, sources }) {
  if (!DATE.test(String(releaseDate || ''))) throw new Error('promotion_release_date_invalid');
  for (const [name, sha] of Object.entries(sources || {})) {
    if (!SHA.test(String(sha || ''))) throw new Error(`promotion_source_sha_invalid:${name}`);
  }
  for (const required of ['burrow', 'burrowBackend', 'burrowUi', 'nodeGoblin', 'goblinSecretStore', 'burrowSkills', 'burrowBackdoor']) {
    if (!sources?.[required]) throw new Error(`promotion_source_missing:${required}`);
  }
}

function archiveTracked(root, output, spec) {
  fs.rmSync(output, { recursive: true, force: true });
  fs.mkdirSync(output, { recursive: true });
  const archive = path.join(output, '.snapshot.tar');
  execFileSync('git', ['archive', '--format=tar', `--output=${archive}`, 'HEAD', '--', ...spec.paths], { cwd: root, stdio: 'inherit' });
  execFileSync('tar', ['-xf', archive, '-C', output], { stdio: 'inherit' });
  fs.rmSync(archive);
  for (const relative of spec.excludes) fs.rmSync(path.join(output, relative), { recursive: true, force: true });
}

function stampBurrow(root, version, sources) {
  stampJson(path.join(root, 'backend/package.json'), version);
  stampJson(path.join(root, 'backend/package-lock.json'), version);
  fs.writeFileSync(path.join(root, 'backend/src/release-version.mjs'), `// Generated by public promotion. Do not edit.\nexport const releaseVersion = '${version}';\n`);
  const lines = fs.readFileSync(path.join(root, 'SOURCE_VERSIONS'), 'utf8').trim().split(/\r?\n/);
  lines[0] = `Burrow-Build-Version ${version}`;
  fs.writeFileSync(path.join(root, 'SOURCE_VERSIONS'), `${lines.join('\n')}\n`);
  writeJson(path.join(root, 'backend/RELEASE_PROVENANCE.json'), {
    assembly: version,
    backend: sources.burrowBackend,
    ui: sources.burrowUi
  });
  writeJson(path.join(root, 'PUBLIC_RELEASE.json'), { schemaVersion: 1, releaseDate: version, sources });
}

function stampNodeGoblin(root, version, sources) {
  stampJson(path.join(root, 'burrow.mod.json'), version);
  stampJson(path.join(root, 'gateway/package.json'), version);
  fs.writeFileSync(path.join(root, 'gateway/VERSION'), `${version}\n`);
  writeJson(path.join(root, 'PUBLIC_RELEASE.json'), { schemaVersion: 1, releaseDate: version, sources });
}

function stampGss(root, version, sources) {
  stampJson(path.join(root, 'burrow.mod.json'), version);
  stampJson(path.join(root, 'package.json'), version);
  writeJson(path.join(root, 'PUBLIC_RELEASE.json'), { schemaVersion: 1, releaseDate: version, sources });
}

function stampSkills(root, version, sources) {
  writeJson(path.join(root, 'PUBLIC_RELEASE.json'), { schemaVersion: 1, releaseDate: version, sources });
}

function stampBackdoor(root, version, sources) {
  stampJson(path.join(root, 'burrow.mod.json'), version);
  stampJson(path.join(root, 'package.json'), version);
  stampJson(path.join(root, 'package-lock.json'), version);
  writeJson(path.join(root, 'PUBLIC_RELEASE.json'), { schemaVersion: 1, releaseDate: version, sources });
}

export function stageSnapshots({ roots, outputRoot, releaseDate, sources }) {
  validateInputs({ releaseDate, sources });
  const staged = {};
  for (const [id, spec] of Object.entries(TARGETS)) {
    const root = path.resolve(roots[id]);
    const actual = run('git', ['rev-parse', 'HEAD'], { cwd: root });
    const sourceKey = id === 'burrow' ? 'burrow' : id;
    if (actual !== sources[sourceKey]) throw new Error(`promotion_checkout_mismatch:${id}`);
    const directory = { burrow: 'Burrow', nodeGoblin: 'Node-Goblin', goblinSecretStore: 'Goblin-Secret-Store', burrowSkills: 'Burrow-Skills', burrowBackdoor: 'Burrow-Backdoor' }[id];
    const output = path.resolve(outputRoot, directory);
    archiveTracked(root, output, spec);
    staged[id] = output;
  }
  stampBurrow(staged.burrow, releaseDate, sources);
  stampNodeGoblin(staged.nodeGoblin, releaseDate, sources);
  stampGss(staged.goblinSecretStore, releaseDate, sources);
  stampSkills(staged.burrowSkills, releaseDate, sources);
  stampBackdoor(staged.burrowBackdoor, releaseDate, sources);
  return staged;
}

async function main() {
  const [rootsFile, outputRoot, releaseDate, sourcesFile] = process.argv.slice(2);
  if (!rootsFile || !outputRoot || !releaseDate || !sourcesFile) throw new Error('usage: node stage-snapshots.mjs ROOTS_JSON OUTPUT_ROOT RELEASE_DATE SOURCES_JSON');
  const roots = JSON.parse(fs.readFileSync(path.resolve(rootsFile), 'utf8'));
  const sources = JSON.parse(fs.readFileSync(path.resolve(sourcesFile), 'utf8'));
  stageSnapshots({ roots, outputRoot, releaseDate, sources });
}

