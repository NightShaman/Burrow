const fail = (error, statusCode = 400) => {
  throw Object.assign(new Error(error), { statusCode });
};
const at = () => new Date().toISOString();
const parse = (value) =>
  typeof value === "object" && value !== null
    ? value
    : JSON.parse(value || "{}");
const stable = (value) => {
  if (Array.isArray(value)) return `[${value.map(stable).join(",")}]`;
  if (value && typeof value === "object")
    return `{${Object.keys(value)
      .sort()
      .map((k) => `${JSON.stringify(k)}:${stable(value[k])}`)
      .join(",")}}`;
  return JSON.stringify(value);
};
const sameRequest = (a, b, current) => {
  if (stable(a) === stable(b)) return true;
  // New multi-reference identities bind ordered digests, actor and Mod owner.
  // Saved-default retries may keep their admitted model when the configured
  // default changes, but no other identity field can change on replay.
  if (a?.referenceImages || current.referenceImages) {
    if (!a?.referenceImages || !current.referenceImages || !a.implicitSelection || !current.implicitSelection) return false;
    const withoutSelection = ({ connectionId, modelId, ...identity }) => identity;
    return stable(withoutSelection(a)) === stable(withoutSelection(current));
  }
  if (current.modOwnerId) return false;
  // Never let legacy identities (including the broad implicit-default match)
  // replay an image request with different bytes or a different portrait owner.
  if (a?.useAgentReferenceImage || current.useAgentReferenceImage || a?.referenceImage || current.referenceImage) {
    return !a?.modOwnerId && a?.useAgentReferenceImage === true && current.useAgentReferenceImage === true &&
      current.implicitSelection && a.implicitSelection === true &&
      a.mode === current.mode && a.prompt === current.prompt &&
      a.idempotencyKey === current.idempotencyKey &&
      stable(a.referenceImage) === stable(current.referenceImage);
  }
  try {
    if (
      current.implicitSelection &&
      a?.implicitSelection === true &&
      a.mode === current.mode &&
      a.prompt === current.prompt &&
      a.idempotencyKey === current.idempotencyKey
    )
      return true;
    if (
      Array.isArray(a) &&
      a[2] === current.prompt &&
      a[3] === current.idempotencyKey &&
      a[0] === current.connectionId &&
      a[1] === current.modelId
    )
      return true;
  } catch {}
  return false;
};

export const POSTGRES_FORGE_SCHEMA_SQL = `
CREATE TABLE IF NOT EXISTS forge_jobs (
 id TEXT PRIMARY KEY, agent_id TEXT NOT NULL DEFAULT '__operator__', idem TEXT NOT NULL,
 owner_id TEXT, owner_token TEXT, request JSONB NOT NULL, record JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL,
 ordinal BIGINT GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX IF NOT EXISTS forge_jobs_idem_idx ON forge_jobs (idem, created_at);
CREATE TABLE IF NOT EXISTS forge_selections (
 mode TEXT PRIMARY KEY, connection_id TEXT NOT NULL, model_id TEXT NOT NULL, updated_at TIMESTAMPTZ NOT NULL
);`;

// The injected managed-image store owns storage references. Keep this strict
// projection safe even if that implementation gains private fields later.
function portraitMetadata(image) {
  return image ? Object.fromEntries(['id', 'contentUrl', 'mimeType', 'fileName', 'sizeBytes', 'updatedAt', 'attachmentId']
    .filter(key => image[key] !== undefined).map(key => [key, image[key]])) : null;
}

function publicJob(job) {
  const {
    storageReference,
    agentId,
    legacyAgentId,
    legacySourceAgentId,
    ownerToken,
    ownerId,
    modOwnerId,
    referenceImage,
    referenceImages,
    referenceActorAgentId,
    ...safe
  } = job;
  return {
    ...safe,
    artifacts: (job.artifacts || []).map(({ storageReference: ref, ...a }) => ({
      ...a,
      previewUrl: `/api/forge/jobs/${job.id}/artifacts/${a.id}`,
      downloadUrl: `/api/forge/jobs/${job.id}/artifacts/${a.id}?download=1`,
    })),
  };
}

/** Claims commit under an idempotency advisory lock before paid dispatch.
 * Recovery requires explicit abandoned owner credentials; callers must establish
 * that the owner is stopped. Initialization never interrupts existing work. */
export class PostgresForgeStore {
  constructor({
    pool,
    ownsPool = false,
    resolveAgent,
    resolveOperator,
    runtimeRoot,
    connections,
    resolveConfig,
    referenceImages,
    adapterFactory = createOpenAIGeneratedArtifactAdapter,
    googleAdapterFactory = createGoogleLyriaAdapter,
    ownerId = randomUUID(),
  } = {}) {
    if (!pool?.query || !pool?.connect)
      throw new Error("forge_postgres_pool_required");
    this.pool = normalizePostgresPool(pool);
    this.ownsPool = ownsPool;
    this.resolveAgent = resolveAgent;
    this.resolveOperator =
      resolveOperator ||
      (async () => ({
        operatorId: "default",
        agentWorkspaceRoot: runtimeRoot,
      }));
    this.runtimeRoot = runtimeRoot;
    this.connections = connections;
    this.resolveConfig = resolveConfig;
    this.referenceImages = referenceImages;
    this.adapterFactory = adapterFactory;
    this.googleAdapterFactory = googleAdapterFactory;
    this.ownerId = ownerId;
    this.pending = new Set();
    this.backgroundFailures = new Map();
  }
  async init() {
    return this;
  }
  async close() {
    if (this.ownsPool) await closePostgresPool(this.pool);
  }
  async connectionList(agentId = null) {
    return await (typeof this.connections === "function"
      ? this.connections({agentId})
      : this.connections || []);
  }
  async catalog({agentId = null, includeSavedPortraits = true, includeOwnPortrait = true} = {}) {
    const catalog = forgeCatalog(await this.connectionList(agentId));
    const savedPortraits = includeSavedPortraits ? await this.referenceImages?.list?.() ?? [] : [];
    return { ...catalog, defaults: await this.selections(),
      agentReferenceImages: savedPortraits.map(({ agentId: id, agentName, portraitMetadata: metadata, ...image }) => ({
        agentId: id, agentName, ...portraitMetadata(metadata ?? image),
      })),
      ...(includeOwnPortrait && typeof agentId === 'string' && agentId.trim()
        ? { agentReferenceImage: portraitMetadata(await this.referenceImages?.get?.(agentId) ?? null) }
        : {}),
    };
  }
  snapshotSavedImage(saved, identity) {
    if (!saved?.image || !saved?.bytes) fail('agent_reference_image_missing', 409);
    // A private owned byte copy survives portrait replacement/removal. Only the
    // immutable metadata and content digest enter SQL JSON; never media bytes.
    const bytes = Buffer.isBuffer(saved.bytes) ? Buffer.from(saved.bytes) : null;
    let sourceImages;
    try { sourceImages = validatedSourceImages([{ bytes, mimeType: saved.image.mimeType, name: saved.image.fileName }]); }
    catch { fail('agent_reference_image_invalid', 409); }
    const referenceImage = { ...portraitMetadata(saved.image), ...identity,
      sizeBytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') };
    if (typeof referenceImage.id !== 'string' || !referenceImage.id) fail('agent_reference_image_invalid', 409);
    return { referenceImage: Object.freeze(referenceImage), sourceImages };
  }
  async referenceImageSnapshot(agentId) {
    if (typeof agentId !== 'string' || !agentId.trim()) fail('forge_context_unavailable', 409);
    if (!this.referenceImages?.read) fail('agent_reference_image_missing', 409);
    let saved;
    try { saved = await this.referenceImages.read(agentId); }
    catch (error) {
      if (error?.statusCode === 404 || error?.message === 'agent_not_found') fail('agent_reference_image_missing', 409);
      throw error;
    }
    return this.snapshotSavedImage(saved, { agentId });
  }
  async referenceSnapshots({ agentId, referenceAgentIds, useAgentReferenceImage, catalog, ownerModId, privateReferences, maxBytes }) {
    const snapshots = [];
    let totalBytes = 0;
    const add = snapshot => {
      totalBytes += snapshot.sourceImages.reduce((total, image) => total + image.bytes.length, 0);
      if (totalBytes > maxBytes) fail('reference_images_too_large', 413);
      snapshots.push(snapshot);
    };
    if (privateReferences) {
      if (!this.referenceImages?.readMod) fail('agent_reference_image_missing', 409);
      const seen = new Set();
      for (const { key, id, name } of privateReferences) {
        const identity = `${key}\u0000${id}`;
        if (seen.has(identity)) continue;
        seen.add(identity);
        let saved;
        try { saved = await this.referenceImages.readMod(ownerModId, key, id); }
        catch (error) {
          if (error?.statusCode === 404 || error?.message === 'agent_not_found') fail('agent_reference_image_missing', 409);
          throw error;
        }
        if (saved?.image?.id !== id) fail('agent_reference_image_missing', 409);
        if (totalBytes + (saved?.bytes?.length || 0) > maxBytes) fail('reference_images_too_large', 413);
        add(this.snapshotSavedImage(saved, { key, id, name }));
      }
    } else {
      const ids = [...(useAgentReferenceImage ? [agentId] : []), ...referenceAgentIds];
      const known = new Map(catalog.agentReferenceImages.map(image => [image.agentId, image]));
      for (const id of new Set(ids)) {
        if (typeof id !== 'string' || !id.trim()) fail('forge_context_unavailable', 409);
        // Explicitly requested agents must still have a registered, saved photo.
        if (!known.has(id) && !(id === agentId && useAgentReferenceImage)) fail('agent_reference_image_missing', 409);
        const snapshot = await this.referenceImageSnapshot(id);
        add({ ...snapshot, referenceImage: Object.freeze({ ...snapshot.referenceImage,
          name: known.get(id)?.agentName || id }) });
      }
    }
    return snapshots;
  }
  async selections() {
    const r = await this.pool.query(
      "SELECT mode,connection_id,model_id FROM forge_selections ORDER BY mode",
    );
    return Object.fromEntries(
      r.rows.map((x) => [
        x.mode,
        { connectionId: x.connection_id, modelId: x.model_id },
      ]),
    );
  }
  async setSelection(body) {
    if (
      !body ||
      Array.isArray(body) ||
      Object.keys(body).some(
        (k) => !["mode", "connectionId", "modelId"].includes(k),
      ) ||
      !["mode", "connectionId", "modelId"].every(
        (k) => typeof body[k] === "string" && body[k].trim(),
      ) ||
      !["image", "music", "speech", "video"].includes(body.mode)
    )
      fail("forge_request_invalid");
    const catalog = await this.catalog();
    const m = catalog.models.find(
      (x) =>
        x.connectionId === body.connectionId &&
        x.modelId === body.modelId &&
        x.available &&
        ((body.mode === "image" && x.kind === "image") ||
          (body.mode === "video" && x.kind === "video") ||
          (body.mode === "music" &&
            catalog.music.models?.some(
              (y) =>
                y.connectionId === x.connectionId && y.modelId === x.modelId,
            )) ||
          (body.mode === "speech" &&
            x.kind === "audio" &&
            !catalog.music.models?.some(
              (y) =>
                y.connectionId === x.connectionId && y.modelId === x.modelId,
            ))),
    );
    if (!m) fail("forge_model_unavailable", 409);
    await this.pool.query(
      "INSERT INTO forge_selections(mode,connection_id,model_id,updated_at) VALUES($1,$2,$3,$4) ON CONFLICT(mode) DO UPDATE SET connection_id=EXCLUDED.connection_id,model_id=EXCLUDED.model_id,updated_at=EXCLUDED.updated_at",
      [body.mode, body.connectionId, body.modelId, at()],
    );
    return this.selections();
  }
  async owner() {
    const x = await this.resolveOperator();
    if (!x?.agentWorkspaceRoot) fail("forge_owner_unavailable", 503);
    return x;
  }
  async get(id) {
    const r = await this.pool.query(
      "SELECT record,agent_id FROM forge_jobs WHERE id=$1",
      [id],
    );
    if (!r.rows[0]) fail("forge_job_not_found", 404);
    const job = parse(r.rows[0].record);
    if (job.agentId && !job.legacySourceAgentId)
      job.legacySourceAgentId = job.agentId;
    if (!job.legacySourceAgentId && r.rows[0].agent_id !== "__operator__")
      job.legacySourceAgentId = r.rows[0].agent_id;
    return job;
  }
  async list({ agentId, status, limit, offset } = {}) {
    await this.owner();
    const values = [];
    const where = [];
    for (const [column, value] of [['agent_id', agentId], ['status', status]]) {
      if (value !== undefined) {
        if (typeof value !== 'string' || !value.trim()) fail('forge_request_invalid');
        values.push(value);
        where.push(`${column}=$${values.length}`);
      }
    }
    let sql = `SELECT record FROM forge_jobs${where.length ? ' WHERE ' + where.join(' AND ') : ''} ORDER BY ordinal DESC,id DESC`;
    for (const [clause, value] of [['LIMIT', limit], ['OFFSET', offset]]) {
      if (value !== undefined) {
        if (!Number.isSafeInteger(value) || value < 0) fail('forge_request_invalid');
        values.push(value);
        sql += ` ${clause} $${values.length}`;
      }
    }
    const r = await this.pool.query(sql, values);
    return r.rows.map((x) => this.public(parse(x.record)));
  }
  async archive() {
    await this.owner();
    const result = await this.pool.query('SELECT record FROM forge_archive ORDER BY created_at DESC,id DESC');
    return result.rows.map(row => parse(row.record));
  }
  async delete(id) {
    const owner = await this.owner();
    await withPostgresTransaction(this.pool, async client => {
      const result = await client.query('SELECT record,agent_id FROM forge_jobs WHERE id=$1 FOR UPDATE', [id]);
      if (!result.rows[0]) fail('forge_job_not_found', 404);
      const row = result.rows[0];
      const job = parse(row.record);
      if (!['succeeded', 'failed', 'interrupted'].includes(job.status)) fail('forge_job_active', 409);
      // Refuse file cleanup unless the terminal receipt was durably retained.
      const retained = await client.query('SELECT 1 FROM forge_archive WHERE id=$1', [id]);
      if (!retained.rowCount) fail('forge_archive_missing', 409);
      if (job.agentId && !job.legacySourceAgentId) job.legacySourceAgentId = job.agentId;
      if (!job.legacySourceAgentId && row.agent_id !== '__operator__') job.legacySourceAgentId = row.agent_id;
      const root = await this.sourceRoot(job, owner);
      for (const artifact of job.artifacts || []) {
        if (!artifact.storageReference) continue;
        // Legacy imports may share generated files with other jobs. Chat delivery
        // writes a separate attachment copy and is never a deletion target.
        const shared = await client.query(`SELECT 1 FROM forge_jobs WHERE id<>$1 AND
          record->'artifacts' @> $2::jsonb LIMIT 1`,
          [id, JSON.stringify([{ storageReference: artifact.storageReference }])]);
        if (shared.rowCount) continue;
        if (root) await deleteGeneratedArtifact({ agentWorkspaceRoot: root, storageReference: artifact.storageReference });
      }
      await client.query('DELETE FROM forge_jobs WHERE id=$1', [id]);
    });
    this.backgroundFailures.delete(id);
  }
  async save(job, client = this.pool) {
    job.updatedAt = at();
    const token = job.ownerToken;
    const ownerId = job.ownerId || this.ownerId;
    const r = await client.query(
      "UPDATE forge_jobs SET record=$1,updated_at=$2 WHERE id=$3 AND owner_id=$4 AND owner_token=$5 AND status IN ('queued','running')",
      [JSON.stringify(job), job.updatedAt, job.id, ownerId, token],
    );
    if (!r.rowCount) return false;
    return true;
  }
  async sourceRoot(job, owner) {
    if (job.legacySourceAgentId) {
      const source = await this.resolveAgent(job.legacySourceAgentId);
      if (!source?.agentWorkspaceRoot) fail("forge_artifact_not_found", 404);
      return source.agentWorkspaceRoot;
    }
    return this.runtimeRoot || owner?.agentWorkspaceRoot;
  }
  public(job) {
    const blocker = this.backgroundFailures.get(job.id);
    return publicJob(blocker ? {
      ...job,
      status: "interrupted",
      error: blocker.error,
      errorDetails: null,
      backgroundFailure: { ...blocker },
    } : job);
  }
  selectionMatches(mode, model, catalog) {
    return (
      model?.available &&
      ((mode === "image" && model.kind === "image") ||
        (mode === "video" && model.kind === "video") ||
        (mode === "music" &&
          catalog.music.models?.some(
            (x) =>
              x.connectionId === model.connectionId &&
              x.modelId === model.modelId,
          )) ||
        (mode === "speech" &&
          model.kind === "audio" &&
          !catalog.music.models?.some(
            (x) =>
              x.connectionId === model.connectionId &&
              x.modelId === model.modelId,
          )))
    );
  }
  async create(body, {agentId = null, ownerModId = null, referenceImages: privateReferences = null} = {}) {
    if (!body || typeof body !== "object" || Array.isArray(body))
      fail("forge_request_invalid");
    if ("attachments" in body || "sourceAttachments" in body)
      fail("source_attachments_unsupported");
    if ("options" in body) fail("generation_options_unsupported");
    const keys = [
      "mode",
      "connectionId",
      "modelId",
      "prompt",
      "idempotencyKey",
      "useAgentReferenceImage",
      "referenceAgentIds",
    ];
    if (
      Object.keys(body).some((k) => !keys.includes(k)) ||
      ["prompt", "idempotencyKey"].some(
        (k) => typeof body[k] !== "string" || !body[k].trim(),
      )
    )
      fail("forge_request_invalid");
    if (
      body.mode !== undefined &&
      body.mode !== null &&
      !["image", "music", "speech", "video"].includes(body.mode)
    )
      fail("forge_request_invalid");
    if (body.useAgentReferenceImage !== undefined && body.useAgentReferenceImage !== null && typeof body.useAgentReferenceImage !== 'boolean')
      fail('forge_request_invalid');
    const useAgentReferenceImage = body.useAgentReferenceImage === true;
    if (body.referenceAgentIds != null && (!Array.isArray(body.referenceAgentIds) ||
      body.referenceAgentIds.some(id => typeof id !== 'string' || !id.trim() || id !== id.trim()))) fail('forge_request_invalid');
    const referenceAgentIds = body.referenceAgentIds ?? [];
    if (privateReferences != null && (!ownerModId || !Array.isArray(privateReferences) || !privateReferences.length ||
      privateReferences.some(ref => !ref || Array.isArray(ref) || typeof ref !== 'object' ||
        Object.keys(ref).some(key => !['key', 'id', 'name'].includes(key)) ||
        ['key', 'id', 'name'].some(key => typeof ref[key] !== 'string' || !ref[key].trim())))) fail('forge_request_invalid');
    if (privateReferences && (useAgentReferenceImage || referenceAgentIds.length || body.referenceAgentIds != null)) fail('forge_request_invalid');
    const hasReferences = useAgentReferenceImage || referenceAgentIds.length > 0 || Boolean(privateReferences);
    if (hasReferences && body.mode && body.mode !== 'image') fail('agent_reference_image_image_only');
    const explicit =
      body.connectionId !== undefined || body.modelId !== undefined;
    if (
      explicit &&
      ["connectionId", "modelId"].some(
        (k) => typeof body[k] !== "string" || !body[k].trim(),
      )
    )
      fail("forge_request_invalid");
    if (!explicit && !body.mode) fail("forge_selection_missing", 409);
    const catalog = await this.catalog({ agentId, includeSavedPortraits: !privateReferences && referenceAgentIds.length > 0, includeOwnPortrait: false });
    const saved = explicit
      ? { connectionId: body.connectionId, modelId: body.modelId }
      : (await this.selections())[body.mode];
    if (!saved) fail("forge_selection_missing", 409);
    const model = catalog.models.find(
      (x) =>
        x.connectionId === saved.connectionId && x.modelId === saved.modelId,
    );
    if (
      explicit &&
      body.mode &&
      (!model || !this.selectionMatches(body.mode, model, catalog))
    )
      fail("forge_model_unavailable", 409);
    if (ownerModId !== null && (typeof ownerModId !== 'string' || !/^[a-z0-9][a-z0-9-]{0,63}$/.test(ownerModId))) fail('forge_request_invalid');
    let referenceConfig, referenceConfigurationUnavailable = false;
    if (hasReferences && model?.available && model.agentReferenceImage?.available) {
      try { referenceConfig = await this.resolveConfig(saved.connectionId, saved.modelId); }
      catch { referenceConfigurationUnavailable = true; }
    }
    // Reuse the existing deployment allocation budget, not a new product cap.
    const maxReferenceBytes = mediaBudgets(referenceConfig || {}).total;
    // A changed deployment budget cannot invalidate an already admitted key.
    // The hint bounds snapshot allocation by that key's prior admitted size;
    // exact replay identity is still checked under the claim transaction below.
    let snapshotMaxBytes = maxReferenceBytes;
    if (hasReferences) {
      const prior = await this.pool.query('SELECT request FROM forge_jobs WHERE idem=$1', [body.idempotencyKey]);
      for (const row of prior.rows) {
        const identity = parse(row.request);
        const refs = identity.referenceImages || (identity.referenceImage ? [identity.referenceImage] : []);
        const bytes = refs.reduce((total, ref) => total + (Number.isSafeInteger(ref?.sizeBytes) && ref.sizeBytes > 0 ? ref.sizeBytes : 0), 0);
        if (Number.isSafeInteger(bytes)) snapshotMaxBytes = Math.max(snapshotMaxBytes, bytes);
      }
    }
    // Preserve the self-only identity/prompt for existing callers. New explicit
    // lists (even one other agent), and Theater-owned refs use ordered snapshots.
    const legacySelf = useAgentReferenceImage && !referenceAgentIds.length && !privateReferences;
    const snapshots = legacySelf ? [await this.referenceImageSnapshot(agentId)] : hasReferences
      ? await this.referenceSnapshots({ agentId, referenceAgentIds, useAgentReferenceImage, catalog, ownerModId, privateReferences, maxBytes: snapshotMaxBytes }) : [];
    const referenceImage = legacySelf ? snapshots[0].referenceImage : null;
    const multiReferences = hasReferences && !legacySelf ? snapshots.map(({ referenceImage: ref }) => privateReferences
      ? { key: ref.key, id: ref.id, name: ref.name, mimeType: ref.mimeType, sizeBytes: ref.sizeBytes, sha256: ref.sha256 }
      : ref) : null;
    const dispatch = snapshots.length ? { sourceImages: snapshots.flatMap(snapshot => snapshot.sourceImages) } : null;
    if (dispatch && multiReferences) {
      // Keep the selected identities aligned with the adapter's image order.
      // Only the provider prompt gets this mapping; the job's caller prompt
      // stays unchanged and no single-self exact prompt changes.
      dispatch.prompt = `${body.prompt}\n\nUse the supplied reference images as canonical character identities: preserve each character's face, species, build and distinctive features. Do not blend identities; depict only the characters called for by the scene.\nReference images (in the order supplied):\n${multiReferences.map((ref, index) =>
        `${index + 1}. Image ${index + 1} depicts ${JSON.stringify(ref.name)}${ref.agentId ? ` (agent ${JSON.stringify(ref.agentId)})` : ''}.`).join('\n')}`;
    }
    // Config resolution may borrow this same pool. Resolve before holding the
    // claim transaction (including max-one pools), but defer admission errors
    // until after replay matching so saved-default retries remain valid.
    if (dispatch) {
      dispatch.config = referenceConfig;
      dispatch.configurationUnavailable = referenceConfigurationUnavailable;
    }
    const request = {
      mode: body.mode ?? null,
      connectionId: saved.connectionId,
      modelId: saved.modelId,
      prompt: body.prompt,
      idempotencyKey: body.idempotencyKey,
      implicitSelection: !explicit,
      ...(ownerModId ? { modOwnerId: ownerModId } : {}),
      ...(referenceImage ? { useAgentReferenceImage: true, referenceImage } : {}),
      ...(multiReferences ? { referenceImages: multiReferences,
        referenceActorAgentId: agentId || null,
        ...(useAgentReferenceImage ? { useAgentReferenceImage: true } : {}) } : {}),
    };
    const owner = await this.owner();
    let result;
    try {
      result = await withPostgresTransaction(this.pool, async (client) => {
        await client.query(
          "SELECT pg_advisory_xact_lock(hashtextextended($1, 0))",
          [request.idempotencyKey],
        );
        const found = await client.query(
          "SELECT request,record FROM forge_jobs WHERE idem=$1 ORDER BY ordinal ASC",
          [request.idempotencyKey],
        );
        const matching = found.rows.find((row) =>
          sameRequest(parse(row.request), request, request),
        );
        if (found.rows.length && !matching) fail("idempotency_conflict", 409);
        if (matching) {
          return {
            job: publicJob(parse(matching.record)),
            replayed: true,
          };
        }
        if (!model?.available) fail("forge_model_unavailable", 409);
        if (dispatch) {
          if (dispatch.sourceImages.reduce((total, image) => total + image.bytes.length, 0) > maxReferenceBytes) fail('reference_images_too_large', 413);
          if (model.kind !== 'image') fail('agent_reference_image_image_only');
          if (!model.agentReferenceImage?.available) fail('agent_reference_image_unsupported', 409);
          if (dispatch.configurationUnavailable) fail('forge_model_unavailable', 409);
          if (!referenceImageCapability(dispatch.config).available) fail('agent_reference_image_unsupported', 409);
        }
        const job = {
          id: randomUUID(),
          ...request,
          ownerToken: randomUUID(),
          ownerId: this.ownerId,
          kind: model.kind,
          status: "queued",
          createdAt: at(),
          updatedAt: at(),
          error: null,
          artifacts: [],
        };
        await client.query(
          "INSERT INTO forge_jobs(id,agent_id,idem,owner_id,owner_token,request,record,created_at,updated_at) VALUES($1,$2,$3,$4,$5,$6,$7,$8,$8)",
          [
            job.id,
            "__operator__",
            job.idempotencyKey,
            this.ownerId,
            job.ownerToken,
            JSON.stringify(request),
            JSON.stringify(job),
            job.createdAt,
          ],
        );
        await client.query(
          "INSERT INTO forge_idempotency_claims(idem,first_job_id) VALUES($1,$2)",
          [job.idempotencyKey, job.id],
        );
        return { job: publicJob(job), replayed: false, raw: job };
      });
    } catch (error) {
      if (error?.code !== "23505") throw error;
      const found = await this.pool.query(
        "SELECT request,record FROM forge_jobs WHERE idem=$1 ORDER BY ordinal ASC",
        [request.idempotencyKey],
      );
      const matching = found.rows.find((row) =>
        sameRequest(parse(row.request), request, request),
      );
      if (!matching) fail("idempotency_conflict", 409);
      result = { job: publicJob(parse(matching.record)), replayed: true };
    }
    if (!result.replayed) {
      const task = Promise.resolve()
        .then(() => this.run(result.raw, owner, dispatch))
        .catch(async () => {
          // Own the failure even when the failed-state receipt cannot be saved.
          // Never retain driver/provider messages, which may contain secrets.
          const job = result.raw;
          const blocker = { error: "forge_background_persistence_failed", updatedAt: at() };
          this.backgroundFailures.set(job.id, blocker);
          job.status = "interrupted";
          job.error = blocker.error;
          job.errorDetails = null;
          try { await this.save(job); } catch { /* explicit recovery remains available */ }
          console.error("Forge background persistence failed; interrupted receipt reconciliation attempted");
        })
        .finally(() => this.pending.delete(task));
      this.pending.add(task);
    }
    return { job: result.job, replayed: result.replayed };
  }
  async run(job, owner, dispatch = null) {
    let stage = "configuration",
      config;
    try {
      const claimed = await this.pool.query(
        "SELECT 1 FROM forge_jobs WHERE id=$1 AND owner_id=$2 AND owner_token=$3 AND status IN ('queued','running')",
        [job.id, job.ownerId || this.ownerId, job.ownerToken],
      );
      if (!claimed.rowCount) return;
      if (
        job.status === "succeeded" ||
        job.status === "failed" ||
        job.status === "interrupted"
      )
        return;
      job.status = "running";
      if (!(await this.save(job))) return;
      config = dispatch?.config ?? await this.resolveConfig(job.connectionId, job.modelId);
      if ((job.useAgentReferenceImage || job.referenceImages?.length) && (!dispatch?.sourceImages?.length || !referenceImageCapability(config).available))
        throw new Error('agent_reference_image_snapshot_unavailable');
      const nativeGoogle = googleNativeApi(config) && googleMediaKind(config) === job.kind;
      const google = job.kind === "audio" && googleLyriaSupported(config) && googleMediaKind(config) === "audio";
      if (
        !config ||
        (!google && !nativeGoogle &&
          (generatedArtifactKind(config) !== job.kind ||
            !/^openai-/.test(config.api)))
      )
        throw new Error("unavailable");
      const adapter = nativeGoogle
        ? createGoogleMediaAdapter({ config })
        : google
        ? this.googleAdapterFactory({ config })
        : this.adapterFactory({ config });
      stage = "provider";
      job.calls = [{ connectionId: job.connectionId, modelId: job.modelId, startedAt: at(), status: 'running' }];
      if (!(await this.save(job))) return;
      const result = await adapter.complete({ prompt: dispatch?.prompt ?? job.prompt, ...(dispatch?.sourceImages ? { sourceImages: dispatch.sourceImages } : {}) });
      if (!result.ok || !result.outputArtifacts?.length)
        throw Object.assign(
          new Error(result.error || "Provider returned no artifacts"),
          {
            errorDetails: {
              ...result.errorDetails,
              message:
                result.errorDetails?.message ||
                result.error ||
                "Provider returned no artifacts",
              httpStatus:
                result.errorDetails?.httpStatus ||
                result.status ||
                result.httpStatus,
            },
          },
        );
      job.calls[0].status = 'succeeded';
      job.calls[0].completedAt = at();
      stage = "artifact_storage";
      for (const artifact of result.outputArtifacts) {
        const stored = await persistGeneratedArtifact({
          agentWorkspaceRoot:
            (await this.sourceRoot(job, owner)) ||
            this.runtimeRoot ||
            owner.agentWorkspaceRoot,
          metadata: artifact,
          bytes: artifact.source?.bytes,
        });
        job.artifacts.push({
          id: randomUUID(),
          kind: stored.kind,
          name: stored.name,
          mimeType: stored.mimeType,
          sizeBytes: stored.sizeBytes,
          storageReference: stored.storageReference,
        });
      }
      job.status = "succeeded";
      if (!(await this.save(job))) throw new Error("forge_job_ownership_lost");
    } catch (error) {
      if (job.calls?.[0]?.status === 'running') {
        job.calls[0].status = 'failed';
        job.calls[0].completedAt = at();
      }
      const retained = [];
      for (const a of job.artifacts) {
        try {
          const root = await this.sourceRoot(job, owner);
          const x =
            root &&
            (await resolveGeneratedArtifact({
              agentWorkspaceRoot: root,
              storageReference: a.storageReference,
            }));
          if (x) await fs.rm(x.filePath, { force: true });
        } catch {
          retained.push(a);
        }
      }
      job.artifacts = retained;
      job.status = "failed";
      job.error = "generation_failed";
      job.errorDetails = diagnostic(error, stage, config);
      await this.save(job);
    }
  }
  async artifact(id, artifactId) {
    const job = await this.get(id);
    const owner = await this.owner();
    const artifact = job.artifacts.find((x) => x.id === artifactId);
    if (!artifact) fail("forge_artifact_not_found", 404);
    const root = await this.sourceRoot(job, owner);
    const resolved =
      root &&
      (await resolveGeneratedArtifact({
        agentWorkspaceRoot: root,
        storageReference: artifact.storageReference,
      }));
    if (!resolved) fail("forge_artifact_not_found", 404);
    return { owner, job, artifact, resolved };
  }
  async attach(id, body) {
    if (
      !body ||
      Object.keys(body).some(
        (k) => !["agentId", "sessionId", "artifactId"].includes(k),
      ) ||
      ["agentId", "sessionId", "artifactId"].some(
        (k) => typeof body[k] !== "string" || !body[k],
      ) ||
      !/^[A-Za-z0-9._-]{1,120}$/.test(body.sessionId) ||
      [".", ".."].includes(body.sessionId) ||
      body.sessionId.startsWith("-") ||
      body.sessionId.endsWith("-")
    )
      fail("forge_request_invalid");
    const destination = await this.resolveAgent(body.agentId);
    if (
      !destination?.agentWorkspaceRoot ||
      destination.agentId !== body.agentId
    )
      fail("session_not_found", 404);
    const { job, artifact, resolved } = await this.artifact(
      id,
      body.artifactId,
    );
    if (job.status !== "succeeded") fail("forge_job_not_succeeded", 409);
    const conversations = new PostgresSessionStore({ pool: this.pool });
    const scope = { agentId: body.agentId, sessionId: body.sessionId };
    if (!(await conversations.getMetadata(scope))) fail("session_not_found", 404);
    // Serialize delivery by job/destination. Retries reuse both the existing turn
    // and its attachment file, not merely the underlying generated artifact.
    const key = `forge:${job.id}:${artifact.id}`;
    let copiedPath;
    let entry;
    try {
      entry = await withPostgresTransaction(this.pool, async client => {
        await client.query('SELECT pg_advisory_xact_lock(hashtextextended($1,0))', [`forge-delivery:${body.agentId}:${body.sessionId}:${key}`]);
        const live = await client.query('SELECT 1 FROM forge_jobs WHERE id=$1 FOR SHARE', [id]);
        if (!live.rowCount) fail('forge_job_not_found', 404);
        await client.query('SELECT 1 FROM conversation_sessions WHERE agent_id=$1 AND session_id=$2 FOR UPDATE',[body.agentId,body.sessionId]);
        const prior = await findSessionReplay(client, body.agentId, body.sessionId, null, key);
        if (prior) return prior.entry;
        const bytes = await fs.readFile(resolved.filePath);
        const [stored] = await persistChatAttachments({ retentionDays: (await new PostgresAlbdruckStore({ pool: postgresTransactionContext(client), resolveOriginal: ref => conversations.resolveOriginal(ref), searchHistory: input => conversations.history(input) }).readRetention()).attachmentDays, agentWorkspaceRoot: destination.agentWorkspaceRoot, attachments: [{ name: artifact.name, type: artifact.mimeType, content: `data:${artifact.mimeType};base64,${bytes.toString('base64')}` }] });
        const { content, ...metadata } = stored;
        copiedPath = path.join(destination.agentWorkspaceRoot, metadata.artifactPath);
        const value = buildSessionEntry({sessionId:body.sessionId,type:'message',role:'user',content:'',metadata:{attachments:[metadata],idempotencyKey:key}});
        await client.query('SELECT 1 FROM conversation_sessions WHERE agent_id=$1 AND session_id=$2 FOR UPDATE',[body.agentId,body.sessionId]);
        await client.query('INSERT INTO conversation_entries(agent_id,session_id,entry_id,idempotency_key,entry,created_at) VALUES($1,$2,$3,$4,$5::json,$6)',[body.agentId,body.sessionId,value.id,key,JSON.stringify(value),value.ts]);
        await client.query('UPDATE conversation_sessions SET updated_at=$3 WHERE agent_id=$1 AND session_id=$2',[body.agentId,body.sessionId,value.ts]);
        return value;
      });
    } catch (error) {
      if (copiedPath) await fs.unlink(copiedPath).catch(() => {});
      throw error;
    }
    const a = entry.metadata.attachments[0];
    return { id: a.artifactPath, ...a, sessionId: body.sessionId };
  }
  async recover({ ownerId, ownerToken } = {}) {
    if (
      typeof ownerId !== "string" ||
      !ownerId ||
      typeof ownerToken !== "string" ||
      !ownerToken ||
      ownerId === this.ownerId
    )
      fail("forge_recovery_invalid");
    const timestamp = at();
    const r = await this.pool.query(
      `UPDATE forge_jobs SET updated_at=$3::text::timestamptz, record=record || jsonb_build_object('status','interrupted','error','generation_interrupted','updatedAt',$3::text) WHERE owner_id=$1 AND owner_token=$2 AND status IN ('queued','running') RETURNING id`,
      [ownerId, ownerToken, timestamp],
    );
    return { recovered: r.rowCount };
  }
}
export default PostgresForgeStore;
