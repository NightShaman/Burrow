// The injected managed-image store owns storage references. Keep this strict
// projection safe even if that implementation gains private fields later.
function portraitMetadata(image) {
  return image ? Object.fromEntries(['id', 'contentUrl', 'mimeType', 'fileName', 'sizeBytes', 'updatedAt', 'attachmentId']
    .filter(key => image[key] !== undefined).map(key => [key, image[key]])) : null;
}

function publicJob(job) {
  const {
    storageReference,
    agentId,
    legacyAgentId,
    legacySourceAgentId,
    ownerToken,
    ownerId,
    modOwnerId,
    referenceImage,
    referenceImages,
    referenceActorAgentId,
    chatDelivery,
    ...safe
  } = job;
  return {
    ...safe,
    ...(chatDelivery ? { delivery: { status: chatDelivery.status, ...(chatDelivery.error ? { error: chatDelivery.error } : {}) } } : {}),
    artifacts: (job.artifacts || []).filter(a => !a.deletedAt).map(({ storageReference: ref, ...a }) => ({
      ...a,
      previewUrl: `/api/forge/jobs/${job.id}/artifacts/${a.id}`,
      downloadUrl: `/api/forge/jobs/${job.id}/artifacts/${a.id}?download=1`,
    })),
  };
}

